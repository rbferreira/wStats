/** Number formatting follows the Windows region; only the wording follows the language. */
export const locale = navigator.language.toLowerCase().startsWith("pt") ? "pt-BR" : "en-US";

export type Language = "auto" | "pt" | "en";
type Strings = typeof pt;

const system: Strings = locale === "pt-BR" ? pt : en;

/** The current strings. A live binding: modules read it when they build their UI. */
export let t: Strings = system;
let current: Language = "auto";
const listeners: (() => void)[] = [];

/** Switches the wording ("auto" = the Windows display language) and tells the pages. */
export function setLanguage(lang: Language | undefined) {
  const next = lang ?? "auto";
  if (next === current) return;
  current = next;
  t = next === "pt" ? pt : next === "en" ? en : system;
  document.documentElement.lang = t === pt ? "pt-BR" : "en";
  listeners.forEach((f) => f());
}

/** Called after the language changes, so a page can rebuild what it already drew. */
export function onLanguageChange(f: () => void) {
  listeners.push(f);
}
